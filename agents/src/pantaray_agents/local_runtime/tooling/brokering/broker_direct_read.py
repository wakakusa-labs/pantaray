"""The Action's read tool, and where it keeps an image the call read.

An image is the one result whose bytes reach the model as themselves, and the
model sees it again on every later turn. History used to name the workspace
file instead, so a later turn read the file again: once the Action rewrote it
(a screenshot regenerated by a test) or anything removed it, the bytes no
longer matched what had been read and every turn after failed. The call keeps
the bytes it read in the user's image store instead, as ``render_pdf_page``
keeps a drawn page and ``capture_screen`` a screenshot, so a later turn sends
exactly what this one saw, and deleting the conversation deletes the copy.
"""

from __future__ import annotations

from pantaray_agents.local_runtime.runtime.local_image_store import (
    write_local_image_blob,
)
from pantaray_agents.tools.files.read import run_read
from pantaray_agents.tools.files.read_contract import ReadToolArgs
from pantaray_agents.tools.files.read_scope import ReadScope

from .broker_outcome import UnprojectedBrokerToolOutcome, read_tool_outcome


def run_read_executor(
    *, scope: ReadScope, request: ReadToolArgs, user_id: str
) -> UnprojectedBrokerToolOutcome:
    result = run_read(scope=scope, request=request)
    image = result.image
    if image is None:
        return read_tool_outcome(result)
    blob = write_local_image_blob(
        user_id=user_id, payload=image.payload, mime_type=image.mime_type
    )
    return UnprojectedBrokerToolOutcome(
        status="success",
        output={
            **result.output,
            # Durable history keeps this output, so the attachment names the
            # kept copy by its user-scoped storage_path, never by path or bytes.
            "attachments": [
                {
                    "type": "file",
                    "source_kind": "local_image_blob",
                    "mime_type": image.mime_type,
                    "path": image.display_path,
                    "storage_path": blob.storage_path,
                    "ref": image.ref,
                    "byte_size": image.byte_size,
                }
            ],
        },
        search_text=result.search_text,
        file_paths=result.file_paths,
        file_reference_paths=result.file_reference_paths,
        attachments=(
            {
                "type": "file",
                "source_kind": "local_image_blob",
                "ref": image.ref,
                "blob_ref": image.blob_ref,
                "display_path": image.display_path,
                "mime_type": image.mime_type,
                "byte_size": image.byte_size,
                "sha256": image.sha256,
                "storage_path": blob.storage_path,
            },
        ),
    )


__all__ = ["run_read_executor"]
